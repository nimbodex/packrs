pub fn encode_char(ch: char) -> Option<&'static str> {
    match ch {
        ' ' => Some("11"),
        't' => Some("1001"),
        'n' => Some("10000"),
        's' => Some("0101"),
        'r' => Some("01000"),
        'd' => Some("00101"),
        '!' => Some("001000"),
        'c' => Some("000101"),
        'm' => Some("000011"),
        'g' => Some("0000100"),
        'b' => Some("0000010"),
        'v' => Some("00000001"),
        'k' => Some("0000000001"),
        'q' => Some("000000000001"),
        'e' => Some("101"),
        'o' => Some("10001"),
        'a' => Some("011"),
        'i' => Some("01001"),
        'h' => Some("0011"),
        'l' => Some("001001"),
        'u' => Some("00011"),
        'f' => Some("000100"),
        'p' => Some("0000101"),
        'w' => Some("0000011"),
        'y' => Some("0000001"),
        'j' => Some("000000001"),
        'x' => Some("00000000001"),
        'z' => Some("000000000000"),
        _ => None,
    }
}
